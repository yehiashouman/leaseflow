CREATE TABLE `CaseReportJob` (
  `id` VARCHAR(191) NOT NULL,
  `ownerUserId` VARCHAR(191) NOT NULL,
  `ownerRole` ENUM('ADMIN', 'LEASING_MANAGER', 'TENANT') NOT NULL,
  `requestId` VARCHAR(191) NOT NULL,
  `clientId` VARCHAR(191) NOT NULL,
  `expectedVersion` INTEGER NOT NULL,
  `status` ENUM('QUEUED', 'RUNNING', 'COMPLETE', 'FAILED') NOT NULL DEFAULT 'QUEUED',
  `snapshot` JSON NOT NULL,
  `snapshotHash` VARCHAR(64) NOT NULL,
  `pdfBytes` MEDIUMBLOB NULL,
  `pdfHash` VARCHAR(64) NULL,
  `attempts` INTEGER NOT NULL DEFAULT 0,
  `retryCount` INTEGER NOT NULL DEFAULT 0,
  `leaseToken` VARCHAR(191) NULL,
  `leaseExpiresAt` DATETIME(3) NULL,
  `failureCode` VARCHAR(191) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `completedAt` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `CaseReportJob_ownerUserId_clientId_key` (`ownerUserId`, `clientId`),
  INDEX `CaseReportJob_status_createdAt_idx` (`status`, `createdAt`),
  INDEX `CaseReportJob_ownerUserId_requestId_createdAt_idx` (`ownerUserId`, `requestId`, `createdAt`),
  CONSTRAINT `CaseReportJob_requestId_fkey` FOREIGN KEY (`requestId`) REFERENCES `Request` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
